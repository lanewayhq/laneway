package fileblock

import (
	"fmt"
	"strings"
)

// Markers around what Laneway writes into a Markdown file. Everything between
// them is Laneway's and is rewritten; everything else is left alone.
const (
	beginMarker = "<!-- laneway:begin (generated by `lane harness add`; edits between these markers are overwritten) -->"
	endMarker   = "<!-- laneway:end -->"
	// beginPrefix finds a begin marker whatever its wording.
	beginPrefix = "<!-- laneway:begin"
)

// mergeBlock puts body between Laneway's markers in doc: in place of the
// marked block if doc has one, else appended after a blank line. It keeps
// doc's line endings.
func mergeBlock(doc, body string) (string, error) {
	nl := "\n"
	if strings.Contains(doc, "\r\n") {
		nl = "\r\n"
	}
	block := strings.ReplaceAll(beginMarker+"\n"+strings.TrimSuffix(body, "\n")+"\n"+endMarker, "\n", nl)

	begin, end, err := findBlock(doc)
	if err != nil {
		return "", err
	}
	if begin >= 0 {
		return doc[:begin] + block + doc[end:], nil
	}
	switch {
	case doc == "":
		return block + nl, nil
	case strings.HasSuffix(doc, nl+nl):
	case strings.HasSuffix(doc, nl):
		doc += nl
	default:
		doc += nl + nl
	}
	return doc + block + nl, nil
}

// removeBlock takes the marked block out of doc, with the blank line that
// mergeBlock put before it. It reports false if doc has no block.
func removeBlock(doc string) (string, bool, error) {
	begin, end, err := findBlock(doc)
	if err != nil || begin < 0 {
		return doc, false, err
	}
	nl := "\n"
	if strings.Contains(doc, "\r\n") {
		nl = "\r\n"
	}
	before, after := doc[:begin], strings.TrimPrefix(doc[end:], nl)
	switch {
	case before == "":
		after = strings.TrimPrefix(after, nl)
	case after == "" || strings.HasPrefix(after, nl):
		before = strings.TrimSuffix(before, nl)
	}
	return before + after, true, nil
}

// findBlock returns the byte offsets of the marked block in doc, from the
// start of its begin marker to the end of its end marker, or -1, -1.
func findBlock(doc string) (begin, end int, err error) {
	begin, end = -1, -1
	offset := 0
	for _, line := range strings.SplitAfter(doc, "\n") {
		text := strings.TrimSpace(line)
		switch {
		case strings.HasPrefix(text, beginPrefix):
			if begin >= 0 {
				return 0, 0, fmt.Errorf("it has two %s… markers; remove one", beginPrefix)
			}
			begin = offset
		case text == endMarker && begin >= 0 && end < 0:
			end = offset + len(strings.TrimRight(line, "\r\n"))
		case text == endMarker:
			return 0, 0, fmt.Errorf("it has a %s marker without a %s… before it", endMarker, beginPrefix)
		}
		offset += len(line)
	}
	if begin >= 0 && end < 0 {
		return 0, 0, fmt.Errorf("it has a %s… marker without a %s after it", beginPrefix, endMarker)
	}
	return begin, end, nil
}
