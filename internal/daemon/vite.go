package daemon

import (
	"encoding/json"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/mrsafalpiya/portby.dev/internal/recipe"
)

// viteConfigVar is replaced, in an HTTP Process's command, with the path of
// a Vite config Portby writes for it (spike #2): the Worktree's own
// vite.config.* with Vite's live-reload WebSocket moved to the Process's
// host on the proxy (wss://vite.<Primary Domain>), and TLS and
// server.origin left to Portby and laravel-vite-plugin. Nothing in the
// Project changes.
const viteConfigVar = "{vite_config}"

// viteConfigs are the files Vite looks for, in its order.
var viteConfigs = []string{"vite.config.js", "vite.config.mjs", "vite.config.ts", "vite.config.cjs", "vite.config.mts", "vite.config.cts"}

// withViteConfig replaces {vite_config} in proc's command with the path of
// the Vite config it writes for proc of the Worktree s. It writes it again
// at every start, so it follows the Worktree's Primary Domain, its
// vite.config.* and the proxy's port. It is kept under the Worktree's own
// Domain, which a new Primary Domain doesn't change.
func (d *Daemon) withViteConfig(s *served, proc recipe.Process) (string, error) {
	if !strings.Contains(proc.Command, viteConfigVar) {
		return proc.Command, nil
	}
	host, ok := d.servedPrimaryDomain(s)
	if !ok {
		host = s.domain
	}
	if !proc.Primary {
		host = proc.Name + "." + host
	}
	path := filepath.Join(d.cfg.Paths.StateDir, "vite", s.domain, proc.Name+".config.mjs")
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return "", err
	}
	if err := os.WriteFile(path, d.viteConfig(s.dir, host), 0o600); err != nil {
		return "", err
	}
	return strings.ReplaceAll(proc.Command, viteConfigVar, shellQuote(path)), nil
}

// viteConfig is the Vite config for the Worktree at dir served at host.
// Vite bundles it with the Project's config, so its import is the Project
// config's absolute path, and it has no other imports: a bare one would
// resolve from Portby's state, not the Project.
func (d *Daemon) viteConfig(dir, host string) []byte {
	_, port, _ := net.SplitHostPort(d.ProxyAddr().String())
	project := "const projectConfig = {};"
	for _, name := range viteConfigs {
		if fi, err := os.Stat(filepath.Join(dir, name)); err == nil && fi.Mode().IsRegular() {
			project = "import projectConfig from " + jsString(filepath.Join(dir, name)) + ";"
			break
		}
	}
	// Vite 8 moved the live-reload settings from server.hmr to server.ws
	// (hmr's are deprecated aliases); earlier versions only know hmr.
	key := "ws"
	if major := viteMajor(dir); major > 0 && major < 8 {
		key = "hmr"
	}
	return fmt.Appendf(nil, `// Generated by Portby for %[1]s. Do not edit: Portby writes it again whenever
// the Process starts. See https://vite.dev/config/server-options.
%[2]s

export default async (env) => {
    const config = typeof projectConfig === 'function' ? await projectConfig(env) : await projectConfig;
    const server = config.server ?? {};
    const hmrOff = server.hmr === false || server.ws === false;

    return {
        ...config,
        server: {
            ...server,
            // Portby's proxy terminates TLS.
            https: false,
            // laravel-vite-plugin derives public/hot from %[3]s.* and, unless
            // origin is set, allows every *.localhost origin (CORS).
            origin: undefined,
            %[3]s: hmrOff ? false : {
                ...(typeof server.%[3]s === 'object' ? server.%[3]s : {}),
                protocol: 'wss',
                host: %[4]s,
                clientPort: %[5]s,
            },
        },
    };
};
`, host, project, key, jsString(host), port)
}

// viteMajor is the major version of the Vite installed in dir, 0 if unknown.
func viteMajor(dir string) int {
	data, err := os.ReadFile(filepath.Join(dir, "node_modules", "vite", "package.json"))
	if err != nil {
		return 0
	}
	var pkg struct{ Version string }
	if json.Unmarshal(data, &pkg) != nil {
		return 0
	}
	major, _, _ := strings.Cut(pkg.Version, ".")
	n, _ := strconv.Atoi(major)
	return n
}

// shellQuote is s as one sh word.
func shellQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// jsString is s as a JavaScript string literal.
func jsString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}
