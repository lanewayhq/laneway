package daemon

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// phpIniDirVar is replaced, in a Process's command, with the directory of
// PHP settings Portby writes for development, for
// `PHP_INI_SCAN_DIR=$PHP_INI_SCAN_DIR:{php_ini_dir} php …`: PHP reads the
// ini files there after its own (the leading ':' of an empty
// $PHP_INI_SCAN_DIR keeps the PHP build's scan dir). The path is absolute,
// since `php artisan serve` runs PHP in public/.
const phpIniDirVar = "{php_ini_dir}"

// phpIni is what Portby sets, with prepend the path of phpPrepend.
//
// php -S (artisan serve's server) caches compiled scripts with OPcache and
// by default only checks every 2 seconds whether they changed, so a page
// reloaded right after a Blade view was edited showed the old view (spike
// #2).
//
// auto_prepend_file runs phpPrepend before every script. It replaces any
// auto_prepend_file of the PHP's own config, which comes earlier.
func phpIni(prepend string) string {
	return fmt.Sprintf(`; Generated by Portby. Do not edit: Portby writes it again whenever a Process
; using {php_ini_dir} starts.
opcache.revalidate_freq=0
auto_prepend_file="%s"
`, prepend)
}

// phpPrepend tells the app that its request came over HTTPS. Portby's
// proxy ends TLS and sends php -S plain HTTP, so without it Laravel builds
// absolute URLs (route(), url(), redirects, signed links) with http://, and
// Portby's HTTP to HTTPS redirect then breaks any request that needs a CORS
// preflight. Laravel would only believe the proxy's X-Forwarded-Proto if the
// app trusted it, which Portby can't do without editing the app. Only php -S
// (the cli-server SAPI) is behind the proxy; commands run with the same
// settings are left alone.
const phpPrepend = `<?php
// Generated by Portby. Do not edit: Portby writes it again whenever a Process
// using {php_ini_dir} starts.
if (PHP_SAPI === 'cli-server') {
    $_SERVER['HTTPS'] = 'on';
}
`

// withPHPIniDir replaces {php_ini_dir} in command with the directory of
// Portby's PHP ini, written again (so an upgraded Portby's settings apply)
// whenever a command uses it.
func (d *Daemon) withPHPIniDir(command string) (string, error) {
	if !strings.Contains(command, phpIniDirVar) {
		return command, nil
	}
	dir := filepath.Join(d.cfg.Paths.StateDir, "php")
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", err
	}
	// PHP reads only *.ini files from a scan dir, so the script can live
	// beside the ini.
	prepend := filepath.Join(dir, "portby-prepend.php")
	if err := os.WriteFile(prepend, []byte(phpPrepend), 0o600); err != nil {
		return "", err
	}
	if err := os.WriteFile(filepath.Join(dir, "portby.ini"), []byte(phpIni(prepend)), 0o600); err != nil {
		return "", err
	}
	return strings.ReplaceAll(command, phpIniDirVar, shellQuote(dir)), nil
}
